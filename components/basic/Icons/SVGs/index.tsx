const Icon: React.FC<ThemeIconProps> = props => {
  const { d, fd: fD, fill, error, filled, size, notif, children, strokeFill } = props;

  const Theme = useDefaultContext().ThemeContext.value;
  const toFill = fill ?? (error ? '#EB5757' : Theme.primary);
  let strokeColor = toFill;
  if (strokeFill) strokeColor = filled ? Theme.primary : Theme.secondary;

  const fontSize = 8;
  const t = notif || 0;
  const r = 30;
  const cx = 100 - r;
  const cy = r;
  const tx = cx;
  const ty = cy + r / 2;
  const getFillnStroke = { fill: strokeFill ? undefined : toFill, stroke: strokeFill ? strokeColor : undefined };

  const renderElement = (element: string | CircleElement, index: number) => {
    if (isString(element)) return <Path key={`path-${index}`} d={element} {...getFillnStroke} />;
    else if (element.type === 'circle') {
      const { type, cx, cy, r, ...circleProps } = element;
      return <Circle key={`circle-${index}`} cx={cx} cy={cy} r={r} {...getFillnStroke} {...circleProps} />;
    }
    return null;
  };
  const renderElements = (data: string | Array<string> | Array<string | CircleElement> | undefined) => {
    if (!data) return null;
    if (Array.isArray(data)) return data.map((v, i) => renderElement(v, i));
    else return renderElement(data, 0);
  };

  return (
    <Svg viewBox={props.viewBox} fill="none" width={size || 0} height={size || 0} {...props}>
      {!filled || !fD ? renderElements(d) : renderElements(fD)}
      {children}
      {t > 0 && (
        <G>
          <Circle cx={cx.toPercent()} cy={cy.toPercent()} r={r.toPercent()} fill="red" />
          <Text x={tx.toPercent()} y={ty.toPercent()} fontSize={fontSize} fill="#fff" textAnchor="middle" fontWeight="bold">
            {t}
          </Text>
        </G>
      )}
    </Svg>
  );
};

